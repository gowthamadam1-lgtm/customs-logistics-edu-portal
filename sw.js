// Service worker for the CLE Portal.
// Keeps a copy of the page and its icons so the installed app opens even on
// a bad connection. Pages are fetched fresh from the network first, so a
// new version shows as soon as it is published; the saved copy is only used
// when the network fails. Requests to other sites (Supabase, fonts, the
// script CDN) are never touched.

const CACHE = 'cle-portal-v2';
const APP_SHELL = [
  './',
  './index.html',
  './manifest.webmanifest',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/icon-maskable-512.png',
];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(APP_SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) {
    return;
  }

  if (request.mode === 'navigate') {
    // Network first: always the newest page, saved copy if offline.
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put('./index.html', copy));
          return response;
        })
        .catch(() => caches.match('./index.html')),
    );
    return;
  }

  // Icons, manifest and other files from this site: saved copy first.
  event.respondWith(caches.match(request).then((cached) => cached || fetch(request)));
});
